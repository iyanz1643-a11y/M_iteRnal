# (이름, 정규식, 옮길 때 할 일). 이 목록이 PostgreSQL 전환의 바꿀 목록이다.
PATTERNS = [
    ("INTEGER PRIMARY KEY 번호 칸", r"\bINTEGER\s+PRIMARY\s+KEY\b", "pg_schema 가 IDENTITY 로 바꾼다. 번호를 직접 넣은 표는 옮긴 뒤 setval 로 맞춘다"),
    ("lastrowid", r"\blastrowid\b", "PgConnection 이 lastval 로 준다. 여러 줄을 넣는 곳은 RETURNING 으로 고친다"),
    ("sqlite_master", r"\bsqlite_master\b", "information_schema.tables 로. 표가 있는지 보는 도우미 하나로 모은다"),
    ("PRAGMA", r"\bPRAGMA\s+\w+", "table_info 는 information_schema.columns 로, foreign_keys 는 지운다"),
    ("executescript", r"\bexecutescript\(", "PgConnection.executescript 가 받는다. 묶음 다시 돌리기는 마이그레이션으로 바꾼다"),
    ("sqlite3 예외와 모듈", r"\bsqlite3\.(OperationalError|IntegrityError|DatabaseError|Error|Row|connect)\b", "DB 별 예외를 한 이름으로 묶는다"),
    ("INSERT OR IGNORE", r"\bINSERT\s+OR\s+IGNORE\b", "translate 가 ON CONFLICT DO NOTHING 으로 바꾼다"),
    ("INSERT OR REPLACE", r"\bINSERT\s+OR\s+REPLACE\b", "손으로 ON CONFLICT (칸) DO UPDATE 로 고친다"),
    ("GROUP_CONCAT", r"\bGROUP_CONCAT\s*\(", "translate 가 string_agg 로 바꾼다"),
    ("IS ? 비교", r"\bIS\s+(NOT\s+)?\?", "translate 가 IS NOT DISTINCT FROM 으로 바꾼다"),
    ("julianday", r"\bjulianday\s*\(", "손으로 날짜 빼기 (x::date - y::date) 로 고친다"),
    ("json_extract", r"\bjson_extract\s*\(", "손으로 (칸::jsonb ->> '열쇠') 로 고친다"),
    ("strftime SQL", r"(?<![.\w])strftime\s*\(\s*'%", "손으로 to_char 로 고친다"),
    ("두 값 MAX 와 MIN", r"\b(MAX|MIN)\((?:[^()]|\([^()]*\))*,", "손으로 GREATEST 와 LEAST 로 고친다"),
    ("참거짓 합", r"\bSUM\(\s*[\w.]+\s+(IS|=|<|>|!=|IN)\b", "손으로 SUM(CASE WHEN ... THEN 1 ELSE 0 END) 로 고친다"),
    ("LIKE 대소문자", r"\bLIKE\b", "SQLite 는 영문 대소문자를 가리지 않는다. 영문을 찾는 곳은 ILIKE 로"),
]


def scan(root: pathlib.Path | None = None) -> list:
    """[(이름, 건수, [파일:줄 ...], 할 일)]. app 아래 .py 와 schema.sql 을 본다. 이 파일은 뺀다."""
    root = root or db.ROOT
    files = sorted((root / "app").rglob("*.py")) + [root / "schema" / "schema.sql"]
    me = pathlib.Path(__file__).resolve()
    out = []
    for name, pat, todo in PATTERNS:
        rx, where = re.compile(pat), []               # SQL 은 큰 글자로 쓰므로 대소문자를 가린다. 파이썬의 max, min 과 섞이지 않는다
        for f in files:
            if f.resolve() == me:
                continue
            for no, line in enumerate(f.read_text(encoding="utf-8").splitlines(), 1):
                if rx.search(line):
                    where.append(f"{f.relative_to(root).as_posix()}:{no}")
        out.append((name, len(where), where, todo))
    return out


def main(argv=None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    cmd = argv[0] if argv else "scan"
    if cmd == "pg-schema":
        sys.stdout.write(pg_schema())
        return 0
    if cmd == "scan":
        for name, n, where, todo in scan():
            print(f"{name}\t{n}\t{todo}")
            for w in where[:8]:
                print(f"    {w}")
            if len(where) > 8:
                print(f"    ... {len(where) - 8}곳 더")
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main())
