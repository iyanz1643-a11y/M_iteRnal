"""SQLite 와 PostgreSQL 의 SQL 차이를 메우는 최소한의 층과 점검.

    python -m app.ops.sqlcompat scan         # 지금 코드의 SQLite 전용 문법을 꼴별로 센다. 파일:줄 을 함께 보인다
    python -m app.ops.sqlcompat pg-schema    # schema.sql 을 PostgreSQL 첫 마이그레이션 꼴로 바꿔 내보낸다

지금 앱은 SQLite 로만 돈다. 이 층은 PostgreSQL 로 옮길 때 같은 SQL 을 두 DB 에서 돌리려는 준비다.

| 바꾸는 것 | SQLite | PostgreSQL |
| --- | --- | --- |
| 자리표시 | ? | %s. 글자 안의 ? 는 그대로, % 는 %% 로 |
| 겹치면 건너뛰기 | INSERT OR IGNORE INTO | INSERT INTO ... ON CONFLICT DO NOTHING |
| 글 이어 붙이기 | GROUP_CONCAT(x, '|') | string_agg(CAST(x AS TEXT), '|') |
| NULL 도 같다고 보는 비교 | a IS ? | a IS NOT DISTINCT FROM %s |
| 번호 칸 | INTEGER PRIMARY KEY | INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY |
| 줄 꼴 | sqlite3.Row 의 r[0], r["칸"], dict(r) | 같은 일을 하는 Row |
| 마지막 번호 | cursor.lastrowid | SELECT lastval() |

자동으로 바꾸지 못하는 것은 NotPortable 을 낸다. INSERT OR REPLACE 처럼 겹침 기준 칸을 알아야 하는 것이다.
그 밖에 손으로 고칠 것의 목록은 PATTERNS 와 scan 결과다. 계획은 보고서와 docs 의 PostgreSQL 절에 있다.
"""
from __future__ import annotations

import pathlib
import re
import sys

from app import db

SQLITE, POSTGRES = "sqlite", "postgres"


class NotPortable(ValueError):
    pass


# ---------------------------------------------------------------- 글자 밖에서만 바꾸기
def _split_literals(sql: str) -> list:
    """[(글자인가, 조각)]. 작은따옴표 글자와 큰따옴표 이름을 글자로 본다. '' 이스케이프를 따른다."""
    out, buf, i, n = [], [], 0, len(sql)
    while i < n:
        ch = sql[i]
        if ch in ("'", '"'):
            if buf:
                out.append((False, "".join(buf)))
                buf = []
            j = i + 1
            while j < n:
                if sql[j] == ch:
                    if j + 1 < n and sql[j + 1] == ch:
                        j += 2
                        continue
                    break
                j += 1
            out.append((True, sql[i:j + 1]))
            i = j + 1
            continue
        buf.append(ch)
        i += 1
    if buf:
        out.append((False, "".join(buf)))
    return out


_GC = re.compile(r"\bGROUP_CONCAT\s*\(", re.I)


def _group_concat(code: str) -> str:
    out, i = [], 0
    for m in _GC.finditer(code):
        if m.start() < i:
            continue
        depth, j, comma = 1, m.end(), None
        while j < len(code) and depth:
            c = code[j]
            if c == "(":
                depth += 1
            elif c == ")":
                depth -= 1
            elif c == "," and depth == 1 and comma is None:
                comma = j
            j += 1
        inner_end = j - 1
        expr = code[m.end():comma if comma is not None else inner_end].strip()
        sep = code[comma + 1:inner_end].strip() if comma is not None else "','"
        out.append(code[i:m.start()])
        out.append(f"string_agg(CAST({expr} AS TEXT), {sep})")
        i = j
    out.append(code[i:])
    return "".join(out)


def translate(sql: str, dialect: str = SQLITE) -> str:
    """SQLite 꼴 SQL 을 그 DB 꼴로. sqlite 면 그대로 돌려준다."""
    if dialect == SQLITE:
        return sql
    if dialect != POSTGRES:
        raise ValueError(dialect)
    if re.search(r"\bINSERT\s+OR\s+REPLACE\b", sql, re.I):
        raise NotPortable("INSERT OR REPLACE 는 겹침 기준 칸을 정해 ON CONFLICT (...) DO UPDATE 로 고쳐야 합니다")
    ignore = bool(re.search(r"\bINSERT\s+OR\s+IGNORE\b", sql, re.I))
    pieces = _split_literals(sql)
    # GROUP_CONCAT 은 구분자가 글자라 조각을 다시 합친 뒤 바꾼다. 글자 안에 GROUP_CONCAT 이라는 말이 없다고 본다
    joined = "".join(p if lit else p for lit, p in pieces)
    if _GC.search(joined):
        pieces = _split_literals(_group_concat(joined))
    out = []
    for lit, p in pieces:
        if lit:
            out.append(p.replace("%", "%%") if p.startswith("'") else p)
            continue
        p = p.replace("%", "%%")
        p = re.sub(r"\bINSERT\s+OR\s+IGNORE\s+INTO\b", "INSERT INTO", p, flags=re.I)
        p = re.sub(r"\bIS\s+NOT\s+\?", "IS DISTINCT FROM ?", p, flags=re.I)
        p = re.sub(r"\bIS\s+\?", "IS NOT DISTINCT FROM ?", p, flags=re.I)
        p = p.replace("?", "%s")
        out.append(p)
    text = "".join(out)
    if ignore and not re.search(r"\bON\s+CONFLICT\b", text, re.I):
        text = text.rstrip().rstrip(";") + " ON CONFLICT DO NOTHING"
    return text


def pg_schema(text: str | None = None) -> str:
    """schema.sql 을 PostgreSQL 첫 마이그레이션 꼴로. 번호 칸만 바꾼다. 나머지 문법은 그대로 돈다(2026-11-15 PostgreSQL 16 에서 확인)."""
    text = text if text is not None else db.SCHEMA.read_text(encoding="utf-8")
    return re.sub(r"\bINTEGER\s+PRIMARY\s+KEY\b", "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", text)


# ---------------------------------------------------------------- 줄과 연결
class Row(tuple):
    """sqlite3.Row 처럼 번호와 칸 이름 둘 다로 읽는다. dict(row) 도 된다."""

    def __new__(cls, names, values):
        r = super().__new__(cls, values)
        r._names = tuple(names)
        r._index = {k: i for i, k in enumerate(r._names)}
        return r

    def __getitem__(self, k):
        if isinstance(k, str):
            return tuple.__getitem__(self, self._index[k])
        return tuple.__getitem__(self, k)

    def keys(self):
        return list(self._names)


class Cursor:
    def __init__(self, cur, conn, is_insert):
        self._cur, self._conn, self._is_insert = cur, conn, is_insert

    def _wrap(self, r):
        if r is None:
            return None
        names = [d[0] for d in (self._cur.description or [])]
        return Row(names, r)

    def fetchone(self):
        return self._wrap(self._cur.fetchone())

    def fetchall(self):
        return [self._wrap(r) for r in self._cur.fetchall()]

    def __iter__(self):
        return iter(self.fetchall())

    @property
    def rowcount(self):
        return self._cur.rowcount

    @property
    def lastrowid(self):
        if not self._is_insert:
            return None
        c = self._conn.cursor()
        try:
            c.execute("SELECT lastval()")
            return c.fetchone()[0]
        except Exception:
            return None


class PgConnection:
    """psycopg 연결을 sqlite3.Connection 처럼 쓰게 하는 얇은 껍데기. 이 환경에는 psycopg 가 없어 시험하지 않았다(가정).

    쓰는 법: PgConnection(psycopg.connect(url)). execute 는 SQLite 꼴 SQL 을 받아 translate 로 바꾼다.
    """
    dialect = POSTGRES

    def __init__(self, raw):
        self.raw = raw
        self.row_factory = None

    def execute(self, sql, params=()):
        cur = self.raw.cursor()
        cur.execute(translate(sql, POSTGRES), tuple(params) if params else None)
        return Cursor(cur, self.raw, sql.lstrip().upper().startswith("INSERT"))

    def executemany(self, sql, seq):
        cur = self.raw.cursor()
        cur.executemany(translate(sql, POSTGRES), [tuple(p) for p in seq])
        return Cursor(cur, self.raw, False)

    def executescript(self, text):
        cur = self.raw.cursor()
        cur.execute(pg_schema(text))
        return Cursor(cur, self.raw, False)

    def commit(self):
        self.raw.commit()

    def rollback(self):
        self.raw.rollback()

    def close(self):
        self.raw.close()


def connect_pg(url: str) -> PgConnection:
    try:
        import psycopg  # noqa: F401  설치는 PostgreSQL 로 옮기는 날 requirements 에 더한다
    except ImportError as e:
        raise RuntimeError("PostgreSQL 연결에는 psycopg 가 필요합니다. 아직 requirements 에 넣지 않았습니다.") from e
    import psycopg
    return PgConnection(psycopg.connect(url))


